export function sofaPhotoMask(photo) {
  const filename = decodeURIComponent(photo.split(/[?#]/)[0].split('/').pop())
  const mask = Object.hasOwn(masks, filename) && masks[filename]
  if (!mask) return null

  const [width, height, ...outlines] = mask
  const polygons = outlines.map(outline => {
    const points = outline.split(' ').map(point => {
      const [x, y] = point.split(',').map(Number)
      return `${x / width * 100}% ${y / height * 100}%`
    })
    return `polygon(${points.join(', ')})`
  })
  return {aspect: width / height, polygons}
}
